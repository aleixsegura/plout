// English strings are the source of truth: this object's shape (via `typeof en`)
// drives the type of every other language, so a missing/mistyped key elsewhere
// fails the build instead of silently falling back at runtime.
// Notice text is assembled from the numbers the exporter ships, so every
// language needs the same three formatters. Money stays in es-ES like the rest
// of the app, whatever the interface language.
